"""Deterministic quadrature of the paper's exact companion second moment.

Run from the project root:
    uv run --with mpmath python research/paper-ac/second_moment_table.py

Positive-coefficient Horner evaluation avoids cancellation near r=1.
The two precision runs are a numerical consistency check, not a certified
quadrature bound. No random samples are used.
"""

import json
from pathlib import Path
import mpmath as mp

ROOT = Path(__file__).resolve().parents[2]
DEGREES = (1, 2, 8, 32, 128)


def second_moment(n, digits):
    with mp.workdps(digits):
        def integrand(r):
            km = mp.mpf(0)
            a = mp.mpf(0)
            for j in range(n - 1, -1, -1):
                km = km * r + 1
                a = a * r + (j + 1) * (n - j)
            k = km * r + 1
            return 2 * km * a / (n * k * k)

        knots = sorted(set([mp.mpf(0), mp.mpf('0.5'),
                            1 - mp.mpf(1) / n, mp.mpf(1)]))
        return +mp.quad(integrand, knots)


def main():
    rows = []
    for n in DEGREES:
        low = second_moment(n, 30)
        high = second_moment(n, 50)
        with mp.workdps(50):
            difference = abs(low - high)
            assert difference < mp.mpf('1e-25')
            if n == 1:
                assert abs(high - 1) < mp.mpf('1e-45')
            if n == 2:
                exact = mp.mpf(2) / 3 + 4 * mp.pi / (9 * mp.sqrt(3))
                assert abs(high - exact) < mp.mpf('1e-45')
            rows.append({
                'degree': n,
                'conditional_second_moment_on_circle': mp.nstr(mp.mpf(2*n)/(n+1), 18),
                'second_moment': mp.nstr(high, 30),
                'second_moment_minus_2_log_n': mp.nstr(high - 2 * mp.log(n), 30),
                'precision_difference': mp.nstr(difference, 8),
            })
        print(n, rows[-1]['second_moment'], flush=True)

    data = {'method': 'mpmath tanh-sinh quadrature; positive Horner evaluation',
            'mpmath_version': mp.__version__, 'precisions': [30, 50],
            'random_samples': 0, 'rows': rows}
    Path(__file__).with_name('second-moments.json').write_text(
        json.dumps(data, indent=2) + '\n')
    lines = []
    for row in rows:
        with mp.workdps(40):
            lines.append(f"{row['degree']} & "
                         f"{float(row['conditional_second_moment_on_circle']):.6f} & "
                         f"{float(row['second_moment']):.6f} & "
                         f"{float(row['second_moment_minus_2_log_n']):.6f} "
                         + r'\\')
    (ROOT / 'paper-sections' / 'second-moment-table.tex').write_text(
        '% Generated by research/paper-ac/second_moment_table.py\n'
        + '\\begin{tabular}{rrrr}\n\\toprule\n'
        + r'$n$ & $\Phi_n(1)$ & $\Estar\Lambda^2$ & $\Estar\Lambda^2-2\log n$\\'
        + '\n\\midrule\n' + '\n'.join(lines)
        + '\n\\bottomrule\n\\end{tabular}\n')


if __name__ == '__main__':
    main()
